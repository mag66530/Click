def seed():
    print("Инициализация базы данных...")
    init_db()
    print("Таблицы созданы.")

    db = get_session()

    for brand_data in BRANDS_SEED:
        existing = db.query(Brand).filter_by(name=brand_data["name"]).first()
        if existing:
            print(f"  Бренд '{brand_data['name']}' уже существует (ID: {existing.id}), пропускаем.")
            continue

        cities = brand_data.pop("cities", [])

        brand = Brand(**brand_data)
        db.add(brand)
        db.flush()  # Получаем brand.id без commit

        for city_name in cities:
            city = City(brand_id=brand.id, city_name=city_name)
            db.add(city)

        print(f"  ✅ Добавлен бренд '{brand.name}' с {len(cities)} городами")

    db.commit()
    db.close()
    print("\nГотово! Не забудьте заменить пароли в БД на реальные.")
    print("Используйте команду /list_brands в боте для проверки.")


if __name__ == "__main__":
    seed()
